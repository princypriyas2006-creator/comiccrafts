"""
ComicCraft - Layout Builder
Organizes comic panels, illustrations, and narrative dialogues into a cohesive comic strip layout.
"""

import logging
from typing import Any, Dict, List, Union
from app.gemini_pro import parse_story_to_panels

logger = logging.getLogger("comiccraft.layout_builder")
logging.basicConfig(level=logging.INFO)


def build_comic_layout(
    outline: List[Dict[str, Any]],
    story_content: Union[str, List[Dict[str, Any]]],
    images: List[str]
) -> List[Dict[str, Any]]:
    """
    Organizes the generated images and full comic story into a structured layout.
    Matches each image with its corresponding panel story.
    
    Args:
        outline: The 5-panel outline list generated by Gemini Flash.
        story_content: Full story text from Gemini Pro or already parsed panels.
        images: List of image paths corresponding to each panel.
        
    Returns:
        A list of dictionaries containing:
        - panel_number: int
        - title: str
        - image_path: str
        - scene_description: str
        - caption: str
        - narration: str
        - dialogue: str
        - image_prompt: str
        - text: combined story text
    """
    logger.info("Assembling and binding comic layout...")
    
    # Parse story content into structured panel blocks if it's a string
    if isinstance(story_content, str):
        parsed_story = parse_story_to_panels(story_content, outline)
    elif isinstance(story_content, list):
        parsed_story = story_content
    else:
        parsed_story = []

    layout = []
    total_panels = len(outline)

    for i in range(total_panels):
        out_panel = outline[i]
        panel_num = out_panel.get("panel_number", i + 1)
        panel_title = out_panel.get("title", f"Panel {panel_num}")
        scene_desc = out_panel.get("scene_description", "")
        img_prompt = out_panel.get("image_prompt", "")
        
        # Get image path
        img_path = images[i] if i < len(images) else ""
        
        # Get story items
        story_item = parsed_story[i] if i < len(parsed_story) else {}
        caption = story_item.get("caption", f"Panel {panel_num} of the epic story.")
        narration = story_item.get("narration", scene_desc)
        dialogue = story_item.get("dialogue", "")
        full_text = story_item.get("full_text", f"{caption}\n{narration}\n{dialogue}")

        layout_item = {
            "panel_number": panel_num,
            "title": panel_title,
            "image_path": img_path,
            "scene_description": scene_desc,
            "caption": caption,
            "narration": narration,
            "dialogue": dialogue,
            "image_prompt": img_prompt,
            "text": full_text
        }
        layout.append(layout_item)

    logger.info(f"Successfully assembled {len(layout)} comic panels into layout.")
    return layout
