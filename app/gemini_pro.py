"""
ComicCraft - Gemini Pro Integration
Module for expanding panel outlines into detailed narration, captions, and character dialogue using Google Gemini Pro.
"""

import json
import logging
import os
import re
from typing import Any, Dict, List
from dotenv import load_dotenv

load_dotenv()

logger = logging.getLogger("comiccraft.gemini_pro")
logging.basicConfig(level=logging.INFO)

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "").strip()

GENAI_CLIENT = None
GENAI_LEGACY = None

if GEMINI_API_KEY and GEMINI_API_KEY != "your_gemini_api_key_here":
    try:
        from google import genai
        GENAI_CLIENT = genai.Client(api_key=GEMINI_API_KEY)
        logger.info("google-genai client initialized successfully for Gemini Pro.")
    except Exception as e:
        logger.warning(f"Could not initialize google-genai for Gemini Pro: {e}")
        try:
            import google.generativeai as legacy_genai
            legacy_genai.configure(api_key=GEMINI_API_KEY)
            GENAI_LEGACY = legacy_genai
            logger.info("google.generativeai initialized successfully for Gemini Pro.")
        except Exception as e_leg:
            logger.warning(f"Could not initialize google.generativeai for Gemini Pro: {e_leg}")


def _generate_fallback_story(
    outline: List[Dict[str, Any]],
    character_name: str = "Hero",
    setting: str = "Fantasy Realm",
    tone: str = "Dramatic"
) -> str:
    """
    Generates rich, tone-specific comic story text with captions, narration, and dialogue
    when API is unavailable.
    """
    logger.info("Generating comic story narrative using dynamic storytelling engine.")
    
    # Tone flavors
    tone_lower = tone.lower()
    
    story_blocks = []
    
    dialogues_map = {
        "dramatic": [
            f'{character_name.upper()}: "I must press onward. There is no turning back now."',
            f'{character_name.upper()}: "What is this power? It has been sleeping for centuries..."',
            f'{character_name.upper()}: "Stand back! I will protect this realm at all costs!"',
            f'{character_name.upper()}: "Together, our resolve cannot be shattered!"',
            f'{character_name.upper()}: "A new path begins. The prophecy has awakened."'
        ],
        "funny": [
            f'{character_name.upper()}: "Okay, note to self: Never accept quests from talking squirrels."',
            f'{character_name.upper()}: "Is it just me, or did that rock just wink at me?"',
            f'{character_name.upper()}: "Whoops! Well, that wasn\'t supposed to explode so loudly!"',
            f'{character_name.upper()}: "Wait, did I actually just pull that off? Pure genius!"',
            f'{character_name.upper()}: "Time for a victory snack. Being legendary makes you hungry."'
        ],
        "light-hearted": [
            f'{character_name.upper()}: "What a glorious day for a grand adventure!"',
            f'{character_name.upper()}: "Look at those wonders! Every path has a story to tell."',
            f'{character_name.upper()}: "No obstacle is too tough with a smile and a good plan!"',
            f'{character_name.upper()}: "We did it! Teamwork turns the impossible into victory!"',
            f'{character_name.upper()}: "The horizon is full of bright tomorrow. Let\'s keep exploring!"'
        ],
        "poetic": [
            f'{character_name.upper()}: "The wind whispers forgotten songs through ancient boughs."',
            f'{character_name.upper()}: "In the mirror of time, even shadows seek the light."',
            f'{character_name.upper()}: "A spark ignites against the encroaching dark."',
            f'{character_name.upper()}: "Harmony restored, where stars converge upon the quiet earth."',
            f'{character_name.upper()}: "May this dawn be an enduring sanctuary."'
        ]
    }
    
    selected_dialogues = dialogues_map.get(tone_lower, dialogues_map["dramatic"])
    
    for idx, panel in enumerate(outline):
        p_num = panel.get("panel_number", idx + 1)
        p_title = panel.get("title", f"Panel {p_num}")
        p_scene = panel.get("scene_description", "")
        
        dialogue = selected_dialogues[idx % len(selected_dialogues)]
        
        caption = f"CAPTION: Inside {setting}, where destiny weaves its unpredictable thread."
        narration = f"NARRATION: {p_scene}"
        
        block = f"--- {p_title} ---\n{caption}\n{narration}\n{dialogue}\n"
        story_blocks.append(block)
        
    return "\n".join(story_blocks)


def generate_story(
    outline: List[Dict[str, Any]],
    character_name: str = "Hero",
    setting: str = "Fantasy Realm",
    tone: str = "Dramatic"
) -> str:
    """
    Expands the 5-panel comic outline into detailed narration and character dialogues
    using Google Gemini Pro.
    
    Args:
        outline: The 5-panel outline list generated by Gemini Flash.
        character_name: Name of the main character.
        setting: Location/world of the story.
        tone: Tone of the comic.
        
    Returns:
        A formatted string containing all panels' stories with captions, narration, and dialogues.
    """
    logger.info(f"Generating full comic story for '{character_name}' with Gemini Pro...")
    
    outline_summary = json.dumps(outline, indent=2)
    
    prompt_text = f"""
You are an award-winning comic book writer known for dynamic visual storytelling.
Expand this 5-panel comic outline into a compelling, panel-by-panel comic script.

Story Details:
- Protagonist: {character_name}
- Setting: {setting}
- Tone / Mood: {tone}

Outline:
{outline_summary}

Requirements:
For EACH of the 5 panels, provide:
1. Panel header (e.g., "--- Panel 1: [Title] ---")
2. CAPTION: A short, punchy comic caption setting the scene atmosphere or mood (1 sentence).
3. NARRATION: Descriptive narration conveying the character's thoughts and actions (1-2 sentences).
4. DIALOGUE: Expressive character speech with character name in caps (e.g., {character_name.upper()}: "Dialogue here!").

Keep the tone consistently {tone}. Make the dialogue natural, impactful, and comic-style.
"""

    if GENAI_CLIENT:
        models_to_try = ["gemini-2.5-pro", "gemini-1.5-pro", "gemini-3.1-pro-preview"]
        for model_name in models_to_try:
            try:
                response = GENAI_CLIENT.models.generate_content(
                    model=model_name,
                    contents=prompt_text
                )
                if response and response.text:
                    logger.info(f"Successfully generated story with {model_name}.")
                    return response.text.strip()
            except Exception as e:
                logger.warning(f"Error calling {model_name} via google-genai: {e}")

    elif GENAI_LEGACY:
        models_to_try = ["gemini-1.5-pro", "gemini-pro"]
        for model_name in models_to_try:
            try:
                model = GENAI_LEGACY.GenerativeModel(model_name)
                response = model.generate_content(prompt_text)
                if response and response.text:
                    logger.info(f"Successfully generated story with legacy {model_name}.")
                    return response.text.strip()
            except Exception as e:
                logger.warning(f"Error calling legacy {model_name}: {e}")

    # 3. Free Zero-Key AI LLM Endpoint (Pollinations AI text API)
    try:
        import requests
        import urllib.parse
        logger.info("Attempting free zero-key AI LLM for comic story dialogues...")
        encoded = urllib.parse.quote(prompt_text)
        res = requests.get(f"https://text.pollinations.ai/{encoded}", timeout=8)
        if res.status_code == 200 and len(res.text.strip()) > 80:
            logger.info("Successfully generated story dialogues using free zero-key AI LLM.")
            return res.text.strip()
    except Exception as e_free:
        logger.info(f"Free online LLM story fallback skipped: {e_free}")

    # 4. Fallback to smart offline storytelling engine if APIs are unreachable
    return _generate_fallback_story(outline, character_name, setting, tone)


def parse_story_to_panels(story_text: str, outline: List[Dict[str, Any]]) -> List[Dict[str, str]]:
    """
    Parses the combined story text into structured per-panel components:
    caption, narration, dialogue, and full panel text.
    """
    panels_data = []
    
    # Try splitting by panel marker
    raw_blocks = re.split(r"(?:---|###|\*\*Panel\s*\d|\bPanel\s*\d+:)", story_text)
    blocks = [b.strip() for b in raw_blocks if b.strip()]
    
    for idx, panel in enumerate(outline):
        p_num = panel.get("panel_number", idx + 1)
        title = panel.get("title", f"Panel {p_num}")
        
        # Match corresponding block if possible
        block_text = blocks[idx] if idx < len(blocks) else ""
        
        # Extract CAPTION, NARRATION, DIALOGUE
        caption = ""
        narration = ""
        dialogue = ""
        
        cap_match = re.search(r"CAPTION:\s*(.*?)(?=(?:NARRATION:|DIALOGUE:|\n\n|$))", block_text, re.DOTALL | re.IGNORECASE)
        if cap_match:
            caption = cap_match.group(1).strip()
            
        narr_match = re.search(r"NARRATION:\s*(.*?)(?=(?:DIALOGUE:|CAPTION:|\n\n|$))", block_text, re.DOTALL | re.IGNORECASE)
        if narr_match:
            narration = narr_match.group(1).strip()
        else:
            # Fall back to scene description if narration wasn't explicitly parsed
            narration = panel.get("scene_description", "")
            
        dia_match = re.search(r"([A-Z0-9_\s]+:\s*\"[^\"]+\"|[A-Z0-9_\s]+:\s*[^\n]+)", block_text)
        if dia_match:
            dialogue = dia_match.group(1).strip()
            
        if not caption:
            caption = f"The story unfolds across {panel.get('title', f'Panel {p_num}')}."
        if not dialogue:
            dialogue = f'HERO: "Onward with courage!"'
            
        panels_data.append({
            "panel_number": p_num,
            "title": title,
            "caption": caption,
            "narration": narration,
            "dialogue": dialogue,
            "full_text": block_text or f"{caption}\n{narration}\n{dialogue}"
        })
        
    return panels_data
